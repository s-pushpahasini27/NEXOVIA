"""Apply the existing small SQLite schema to the connected Neon PostgreSQL database.

The application keeps its local SQLite migrations intact.  Only SQLite's FTS5
virtual table and implicit row id need PostgreSQL-specific equivalents.
"""

from pathlib import Path

from .db import ROOT


POSTGRES_SEARCH = """
ALTER TABLE tutor_messages ADD COLUMN provider TEXT NOT NULL DEFAULT 'legacy';
ALTER TABLE tutor_messages ADD COLUMN sources TEXT NOT NULL DEFAULT '[]';
CREATE TABLE resource_chunks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_id TEXT NOT NULL REFERENCES resources(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL,
 ordinal INTEGER NOT NULL,
 content TEXT NOT NULL,
 UNIQUE(resource_id, ordinal)
);
CREATE INDEX resource_chunks_owner ON resource_chunks(user_id, resource_id);
CREATE INDEX resource_chunks_search ON resource_chunks USING GIN (to_tsvector('simple', content));
CREATE TABLE card_schedule (
 user_id TEXT NOT NULL,
 deck_id TEXT NOT NULL REFERENCES decks(id) ON DELETE CASCADE,
 card INTEGER NOT NULL,
 interval_days REAL NOT NULL DEFAULT 0,
 repetitions INTEGER NOT NULL DEFAULT 0,
 due TEXT NOT NULL,
 PRIMARY KEY(user_id,deck_id,card)
);
CREATE INDEX card_schedule_due ON card_schedule(user_id,due);
"""


def statements(file: Path):
    source = POSTGRES_SEARCH if file.name.startswith('0006_') else file.read_text()
    source = source.replace('--> statement-breakpoint', '').replace('`', '"')
    return [part.strip() for part in source.split(';') if part.strip()]


def initialize_postgres(db):
    # Cold starts may race; keep one schema migrator active per database.
    db.execute('SELECT pg_advisory_xact_lock(781242164)')
    db.execute('CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY)')
    for file in sorted((ROOT / 'backend/migrations').glob('*.sql')):
        if db.execute('SELECT 1 FROM schema_migrations WHERE name=?', (file.name,)).fetchone():
            continue
        for statement in statements(file):
            db.execute(statement)
        db.execute('INSERT INTO schema_migrations (name) VALUES (?)', (file.name,))
    db.execute('ALTER TABLE tutor_messages ADD COLUMN IF NOT EXISTS sequence BIGINT GENERATED BY DEFAULT AS IDENTITY')
    db.execute('CREATE INDEX IF NOT EXISTS tutor_messages_sequence ON tutor_messages(user_id, created DESC, sequence DESC)')
